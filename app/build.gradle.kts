val gsConfigFile: File = layout.projectDirectory.file("google-services.json").asFile
val targetApplicationId: String = android.defaultConfig.applicationId ?: ""

tasks.register("verifyFirebaseConfig") {
  description = "Fails build if package name does not match google-services.json or Web Client ID is missing"
  val configFile = gsConfigFile
  val appId = targetApplicationId
  doLast {
    if (!configFile.exists()) {
      throw GradleException("Missing /app/google-services.json. Please see docs/FIREBASE_SETUP.md")
    }
    val content = configFile.readText()
    if (!content.contains("\"package_name\": \"$appId\"") && !content.contains("\"package_name\":\"$appId\"")) {
      throw GradleException("Package name mismatch: applicationId '$appId' was not found in /app/google-services.json. See docs/FIREBASE_SETUP.md")
    }
    if (!content.contains("\"client_type\": 3") && !content.contains("\"client_type\":3")) {
      throw GradleException("Missing Web/Server Client ID (client_type: 3) in /app/google-services.json. See docs/FIREBASE_SETUP.md")
    }
  }
}

tasks.named("preBuild") {
  dependsOn("verifyFirebaseConfig")
}

